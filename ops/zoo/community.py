def cmd_hardware(only=None):
    """Open issues only, against our actual silicon.

    The question here is what is CURRENTLY broken that could bite this fleet,
    not what has ever been wrong, so every search carries state:open. Closed
    issues are history; the model dossiers keep those because a closed bug still
    explains a behaviour we might be seeing on an older build.
    """
    src = tomllib.loads(SOURCES.read_text())
    terms = src["defaults"]["concern_terms"]
    stacks = src.get("stack", {})
    stamp = subprocess.run(["date", "-I"], capture_output=True,
                           text=True).stdout.strip()

    targets = {k: v for k, v in src.get("hardware", {}).items()
               if not only or k == only}
    if not targets:
        print(f"no such hardware target: {only}")
        return 1

    for key, cfg in targets.items():
        print(f"=== {key}: {cfg['label']}")
        blocks = []
        for sname in cfg.get("stacks", []):
            st = stacks.get(sname)
            if not st:
                continue
            for term in cfg.get("terms", []):
                res = gh_issues(st["github"], term, terms, extra="+state:open")
                if res is None:
                    blocks.append({"label": f"{st['github']} `{term}`",
                                   "tier": st["tier"],
                                   "error": "github search failed"})
                    print(f"  {st['github']} {term}: UNREACHABLE")
                    continue
                rows, total = res
                blocks.append({"label": f"{st['github']} `{term}` (open)",
                               "tier": st["tier"], "rows": rows, "total": total})
                print(f"  {st['github']} {term}: {total} open, "
                      f"{sum(1 for r in rows if r['hits'])} flagged")

        blocks.sort(key=lambda b: b["tier"])
        claimed, dropped = set(), 0
        for b in blocks:
            if b.get("error"):
                continue
            keep = []
            for r in b["rows"]:
                k = (r["src"], r["repo"], r["id"])
                if k in claimed:
                    dropped += 1
                    continue
                claimed.add(k)
                keep.append(r)
            b["rows"] = keep
        if dropped:
            print(f"  deduped {dropped} rows already listed under another term")

        body = render(key, cfg, {"refreshed": stamp, "blocks": blocks,
                                 "commits": None, "docs": None})
        DOSSIERS.mkdir(parents=True, exist_ok=True)
        path = DOSSIERS / f"_hw_{key}.md"
        if path.exists():
            old = path.read_text()
            head, tail = old.split(GEN_BEGIN)[0], old.split(GEN_END, 1)[1]
            path.write_text(head + body + tail)
            how = "updated"
        else:
            path.write_text(HW_TEMPLATE.format(
                label=cfg["label"], nodes=", ".join(cfg.get("nodes", [])),
                note=cfg.get("note", ""), generated=body))
            how = "created"
        print(f"  {how} {path.name}")
    return 0


def main():
    ap = argparse.ArgumentParser(description="Community notes for the zoo")
    ap.add_argument("mode", choices=["collect", "hardware", "stub", "thread"])
    ap.add_argument("args", nargs="*")
    ap.add_argument("--model")
    a = ap.parse_args()
    if a.mode == "collect":
        return cmd_collect(a.model)
    if a.mode == "hardware":
        return cmd_hardware(a.model)
    if a.mode == "stub":
        return cmd_stub()
    if len(a.args) != 2:
        ap.error("thread needs <gh|hf> <repo#id>")
    return cmd_thread(a.args[0], a.args[1])


if __name__ == "__main__":
    raise SystemExit(main())
