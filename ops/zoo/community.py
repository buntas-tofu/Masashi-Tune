#!/usr/bin/env python3
"""Community notes: what the field already knows about a vessel we run.

Commissioned by the operator 2026-08-04, after a week in which this fabric
rediscovered several things the field had already written down. His framing:
every new finding that is a rehash of someone else's old finding is drain on a
tokenized system, and at least one token generator here is metered. Not fatal on
its face, but we should stop recreating the wheel.

WHAT THIS IS NOT. It is not a general answer to token burn, and it should not be
judged as one. Almost everything expensive this week was about OUR system and
OUR data: four undecoded PDFs poisoning an anchor set, a repo-shaped migration
blind to gitignored rooms, a reconciler scoped out of the room it was built for.
None of that has an upstream. The value here is concentrated in one class,
vessel behavioural quirks and known defects, and that class is real: the
max_tokens-eaten-by-reasoning trap cost three separate mistakes in two days and
is discussed openly upstream.

THE SECOND BENEFIT IS PROBABLY THE LARGER ONE. The E4B investigation was not
expensive because the answer was unavailable; it was expensive because the
hypothesis space had to be built from nothing. Having the known failure modes in
front of you changes what you test first.

AND IT RUNS BOTH WAYS. The operator's standing rule is to search the field
before claiming a finding and to contribute back where our setup provides a
control others cannot run. That rule currently depends on somebody remembering.
A dossier makes it structural, and every dossier carries a FOR UPSTREAM section
for what we know that the field does not.

DESIGN RULES.

1. Titles are the product. A title plus state, age and comment count is enough
   to decide whether to care, and 45 of them cost about 600 tokens. Full comment
   bodies cost a hundred times that and are mostly noise. Bodies are fetched on
   demand with --thread, never in bulk.
2. Read on demand, never at boot. A dossier hydrated every session costs tokens
   every session for value needed occasionally.
3. Sources are tiered by measured signal, not by guess. See sources.toml.
4. Never scrape around a gate. Doc sites are probed for llms-full.txt and
   llms.txt; if neither exists the source is declined and said so.
5. Authored text is never clobbered. Everything outside the generated block is
   preserved across regeneration, because a lab note is the one thing here that
   cannot be re-fetched.
6. Polite. ETags where the API honours them, one pass, no retry storms. This
   fleet has been IP banned by a scholarly API for being impolite before.

Usage:
  community.py collect [--model KEY]     refresh dossiers from upstream
  community.py stub                      write pointer stubs beside the weights
  community.py thread <src> <id>         fetch one discussion or issue body

Floor: DMF. No em dashes, no ellipses.
"""

